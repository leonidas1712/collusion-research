"""Validate source-backed numeric registry and generate LaTeX macros."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
HERE=Path(__file__).resolve().parent

def pointer(data,path):
    for item in path:data=data[item]
    return data

def render(entry,value):
    kind=entry.get('format','decimal')
    if kind=='integer':return str(int(value))
    if kind=='percent':return f'{100*value:.2f}'+r'\%'
    return f'{value:.2f}'

def generate(check=False):
    registry=json.loads((HERE/'numbers.yaml').read_text()) # JSON is a YAML 1.2 subset.
    lines=['% Generated by generate_numbers.py; edit numbers.yaml, never this file.']
    seen=set();verified=[]
    for key,e in registry['numbers'].items():
        macro=e['macro'];assert re.fullmatch('[A-Za-z]+',macro),macro
        assert macro not in seen;seen.add(macro)
        if e['value'] is None:
            assert e['status']=='pending';lines.append('\\newcommand{\\'+macro+r'}{\texttt{pending}}');continue
        source=ROOT/e['source']['file'];data=json.loads(source.read_text())
        assert source.exists() and (ROOT/e['run']).is_dir()
        value=pointer(data,e['source']['value_path']);assert value==e['value'],(key,value,e['value'])
        ci=e.get('ci')
        if ci is not None:assert pointer(data,e['source']['ci_path'])==ci,key
        lines.append('\\newcommand{\\'+macro+'}{'+render(e,value)+'}')
        if ci is not None:
            for suffix,v in [('Low',ci[0]),('High',ci[1])]:
                assert macro+suffix not in seen;seen.add(macro+suffix)
                lines.append('\\newcommand{\\'+macro+suffix+'}{'+render(e,v)+'}')
            lines.append('\\newcommand{\\'+macro+'CI}{['+render(e,ci[0])+', '+render(e,ci[1])+']}')
        verified.append(dict(key=key,source=str(source.relative_to(ROOT)),sha256=hashlib.sha256(source.read_bytes()).hexdigest()))
    for alias,target in registry.get('aliases',{}).items():
        assert alias not in seen and target in seen;seen.add(alias)
        lines.append('\\newcommand{\\'+alias+'}{\\'+target+'}')
    content='\n'.join(lines)+'\n';out=HERE/'numbers.tex'
    if check:assert out.read_text()==content,'numbers.tex is stale'
    else:out.write_text(content)
    (HERE/'numbers_verification.json').write_text(json.dumps(dict(verified=verified,pending=[k for k,e in registry['numbers'].items() if e['value'] is None]),indent=2)+'\n')
    print(f'{len(verified)} source-verified numbers; {len(registry["numbers"])-len(verified)} pending')

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');generate(p.parse_args().check)
