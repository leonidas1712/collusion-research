#!/usr/bin/env python3
"""Generate explicit draft fallbacks; numbers.tex definitions always take precedence."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
paths = sorted(ROOT.glob('MACRO_REQUESTS_*.md'))
paths += sorted((ROOT / 'sections').glob('*.tex'))
paths += sorted((ROOT / 'appendix').glob('*.tex'))
paths += sorted((ROOT / 'tables').glob('*.tex'))
names = set()
for path in paths:
    names.update(re.findall(r'\\((?:qwen|gptoss|screen)[A-Za-z]+)', path.read_text()))
# A request may specify confidence intervals without spelling out the CI macro.
names |= {name + 'CI' for name in names if not name.endswith('CI')}
text = '% Generated by scripts/generate_pending_macros.py; draft-only fallbacks.\n'
text += ''.join('\\providecommand{\\' + name + '}{\\textbf{pending}}\n' for name in sorted(names))
(ROOT / 'pending_macros.tex').write_text(text)
print(f'{len(names)} numeric macro fallbacks generated')
