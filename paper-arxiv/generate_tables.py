"""Generate numeric table fragments; unavailable analyses remain explicit."""
import json
from pathlib import Path
HERE=Path(__file__).resolve().parent
NAMES=['datasets','behaviour_by_scenario','labels','replay','fresh','robust_call','robust_round','shortcuts','alarms','round_level','history','changed_numbers','repro','monitor_grid']

def main():
    registry=json.loads((HERE/'numbers.yaml').read_text())
    table_dir=HERE/'tables';table_dir.mkdir(exist_ok=True)
    for name in NAMES:
        path=table_dir/(name+'.tex')
        if not path.exists():path.write_text('% Generated pending table; no numerical claims.\n\\begin{tabular}{l}\n\\toprule\nPending verified analysis \\\\\n\\bottomrule\n\\end{tabular}\n')
    configs=registry.get('tables',{})
    for name,spec in configs.items():
        lines=['% Generated by generate_tables.py; edit registry table configuration.',r'\begin{tabular}{'+spec['columns']+'}',r'\toprule',' & '.join(spec['header'])+r' \\',r'\midrule']
        for row in spec['rows']:
            cells=[]
            for cell in row:
                if isinstance(cell,dict):
                    e=registry['numbers'][cell['key']];text='\\'+e['macro']+'{}'
                    if cell.get('ci') and e.get('ci') is not None:text+=' '+('\\'+e['macro']+'CI{}')
                    cells.append(text)
                else:cells.append(cell)
            lines.append(' & '.join(cells)+r' \\')
        lines.extend([r'\bottomrule',r'\end{tabular}'])
        (table_dir/(name+'.tex')).write_text('\n'.join(lines)+'\n')
if __name__=='__main__':main()
